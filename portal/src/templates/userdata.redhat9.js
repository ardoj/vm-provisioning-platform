import { renderUsers } from "./userdata.shared.js";
import { certWriteFiles } from "./certs.js";
import {
  cloudConfigHeader,
  packageUpdateBlock,
  ntpBlock,
  timezoneLine,
  adminsAndUsersHeader,
  commonPackageLines,
  sudoersWriteFile,
  bashPromptWriteFile,
  bashHistoryWriteFile,
  alloyConfWriteFile,
  alloyRepoWriteFiles,
  resolvedDropInWriteFile,
  groupAndHostnameRuncmd,
  setRootPasswordRuncmd,
  alloyRuncmd,
} from "./userdata.common.js";
import { diskBlocks, DEFAULT_DEVICE_PREFIX } from "./userdata.disks.js";
import { profileRuncmd, profilePackages, profileWriteFiles, defaultDisks, PG_DEFAULT_VERSION } from "./profiles.js";

const EL_MAJOR = 9;

export function rhel9UserData(users, opts = {}) {
  const usersYaml = renderUsers(users);
  const {
    gw1 = "", gw2 = "", gw3 = "", nic2 = false, nic3 = false,
    profile = "generic",
    pgVersion = PG_DEFAULT_VERSION,
    devicePrefix = DEFAULT_DEVICE_PREFIX,
  } = opts;
  const disks = opts.disks ?? defaultDisks(profile, "rhel9");
  const ctx = { osFamily: "rhel", elMajor: EL_MAJOR, pgVersion };

  // Routing runcmd block — only emitted when NIC2 (or NIC3) is added.
  // $${...} is Terraform's escape for a literal ${...} in the rendered script.
  // Gateway lines use JS template literals to embed actual IP values.
  const routingRuncmd = nic2 ? [
    "",
    "# Routing — configure additional NICs as non-default",
    `  - INTERFACE_1_GW="${gw1}"`,
    `  - INTERFACE_2_GW="${gw2}"`,
    ...(nic3 ? [`  - INTERFACE_3_GW="${gw3}"`] : []),
    "  - INTERFACES=($(/usr/bin/ip link | grep -o 'ens[0-9]\\+' | sort -u))",
    "  - INTERFACE1=$${INTERFACES[0]}",
    "  - INTERFACE2=$${INTERFACES[1]}",
    ...(nic3 ? ["  - INTERFACE3=$${INTERFACES[2]}"] : []),
    "  - 'if [ -n \"$INTERFACE2\" ]; then nmcli connection modify \"$INTERFACE2\" ipv4.never-default yes ipv6.never-default yes; fi'",
    ...(nic3 ? ["  - 'if [ -n \"$INTERFACE3\" ]; then nmcli connection modify \"$INTERFACE3\" ipv4.never-default yes ipv6.never-default yes; fi'"] : []),
  ] : [];

  // NOTE: ${...} placeholders below are Terraform/cloud-init variables —
  // they are intentionally kept as literal strings and passed through unchanged.
  // Do NOT convert this file to use JS template literals.

  const lines = [
    ...cloudConfigHeader,
    "",
    "rh_subscription:",
    "  activation-key: ak-rhel9",
    "  org: EXAMPLE_ORG",
    "#  auto-attach: true",
    "  rhsm-baseurl: https://satellite.example.internal/pulp/content",
    "  server-hostname: satellite.example.internal",
    "",
    ...packageUpdateBlock(false),
    "",
    ...ntpBlock(),
    "",
    ...diskBlocks(disks, devicePrefix),
    "",
    timezoneLine,
    "",
    ...adminsAndUsersHeader,
    usersYaml,
    "# add extra users below",
    "#  - name: first.last",
    "#    shell: /bin/bash",
    "#    groups: [\"admins\", \"users\"]",
    "#    ssh_authorized_keys:",
    "#      - ssh-rsa AAAA...",
    "",
    "packages:",
    ...commonPackageLines,
    "  - katello-host-tools-tracer",
    "  - lsof",
    "# mail",
    "  - postfix",
    "  - s-nail",
    "# dns cache",
    "  - systemd-resolved",
    "# get needs-restarting bin",
    "  - yum-utils",
    "# monitoring agent",
    "  - alloy",
    ...profilePackages(profile, ctx),
    "",
    "",
    "# passwordless admins group",
    "write_files:",
    ...sudoersWriteFile,
    "",
    ...bashPromptWriteFile,
    "",
    ...bashHistoryWriteFile(true),
    "",
    ...certWriteFiles("/etc/pki/ca-trust/source/anchors"),
    "",
    ...alloyConfWriteFile,
    "",
    ...alloyRepoWriteFiles("rpm"),
    "",
    ...resolvedDropInWriteFile(),
    ...profileWriteFiles(profile, ctx),
    "",
    "runcmd:",
    ...groupAndHostnameRuncmd,
    ...routingRuncmd,
    "# remove template cleanup script",
    "  - [ rm, -f, /root/clean_vm.sh ]",
    setRootPasswordRuncmd,
    "# persistent journal",
    "  - [ /bin/mkdir, -p, /var/log/journal ]",
    "  - [ /bin/chmod, '0755', /var/log/journal ]",
    "  - [ /bin/sed, -i, 's/^#Storage=.*/Storage=persistent/', /etc/systemd/journald.conf ]",
    "  - [ /bin/systemctl, restart, systemd-journald ]",
    "# certs",
    "  - [ update-ca-trust ]",
    "# mail",
    "  - [ /bin/sed, -i, '/^relayhost/d', /etc/postfix/main.cf ]",
    "  - [ /bin/sed, -i, '/^\\#relayhost = \\[an./a relayhost = smtp.example.internal', /etc/postfix/main.cf ]",
    "  - [ /bin/sed, -i, '/^\\#mydomain = domain.tld/a mydomain = example.internal', /etc/postfix/main.cf ]",
    "  - [ /bin/sed, -i, '/^\\#root/a root:    root-alerts@example.com', /etc/aliases ]",
    "  - [ /usr/bin/newaliases ]",
    "  - [ /bin/systemctl, enable, postfix ]",
    "  - [ /bin/systemctl, start, postfix ]",
    "  - [ /bin/systemctl, restart, postfix ]",
    "# DNS cache",
    "  - [ /bin/systemctl, enable, systemd-resolved ]",
    "  - [ /bin/systemctl, start, systemd-resolved ]",
    "  - /bin/sh -c \"if [ -f /run/systemd/resolve/stub-resolv.conf ]; then /usr/bin/mv /etc/resolv.conf /etc/resolv.conf.backup; fi\"",
    "  - /bin/sh -c \"if [ -f /run/systemd/resolve/stub-resolv.conf ]; then /usr/bin/ln -sf /run/systemd/resolve/stub-resolv.conf /etc/resolv.conf; fi\"",
    "  - /bin/sh -c \"if ! [ -L /etc/resolv.conf ]; then /usr/bin/cloud-init clean && /sbin/reboot; fi\"",
    ...alloyRuncmd(),
    "# fix duplicate VMware connection names",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens32\" && (nmcli con del ens32; nmcli con mod \"VMware customization ens32\" connection.id ens32)",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens33\" && (nmcli con del ens33; nmcli con mod \"VMware customization ens33\" connection.id ens33)",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens34\" && (nmcli con del ens34; nmcli con mod \"VMware customization ens34\" connection.id ens34)",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens35\" && (nmcli con del ens35; nmcli con mod \"VMware customization ens35\" connection.id ens35)",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens36\" && (nmcli con del ens36; nmcli con mod \"VMware customization ens36\" connection.id ens36)",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens192\" && (nmcli con del ens192; nmcli con mod \"VMware customization ens192\" connection.id ens192)",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens224\" && (nmcli con del ens224; nmcli con mod \"VMware customization ens224\" connection.id ens224)",
    "  - /bin/nmcli -t -f NAME con show | grep -q \"VMware customization ens256\" && (nmcli con del ens256; nmcli con mod \"VMware customization ens256\" connection.id ens256)",
    ...profileRuncmd(profile, ctx),
    "# reboot checks",
    "  - /bin/sh -c \"if ! /usr/bin/subscription-manager identity > /dev/null 2>&1; then /usr/bin/cloud-init clean && /sbin/reboot; fi\"",
    "  - /bin/sh -c \"if ! [ -f /run/systemd/resolve/stub-resolv.conf ]; then /usr/bin/cloud-init clean && /sbin/reboot; fi\"",
    "# disable cloud-init if systemd-resolved is running",
    "  - /bin/sh -c \"if [ -f /run/systemd/resolve/stub-resolv.conf ]; then /usr/bin/touch /etc/cloud/cloud-init.disabled ; fi\"",
    "  - /bin/sh -c \"if [ -f /run/systemd/resolve/stub-resolv.conf ]; then /usr/bin/systemctl stop cloud-init ; fi\"",
    "  - /bin/sh -c \"if [ -f /run/systemd/resolve/stub-resolv.conf ]; then /usr/bin/systemctl disable cloud-init ; fi\"",
    "  - /bin/sh -c \"if [ -f /run/systemd/resolve/stub-resolv.conf ]; then /usr/bin/dnf remove cloud-init -y; fi\"",
    "# restart if needed",
    "  - /bin/sh -c \"if /usr/bin/needs-restarting -r; then exit 0; else /sbin/reboot; fi\"",
  ];

  return lines.join("\n") + "\n";
}
